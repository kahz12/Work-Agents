import os


class DockerComposeGenerator:
    """
    Generates a hardened docker-compose.yml, parameterised by port, image and resource limits.
    """

    @staticmethod
    def generate_compose_file(
        output_filepath: str,
        *,
        service_name: str = "web",
        image: str = "myorg/myapp:1.0.0",
        port: int = 8080,
        mem_limit: str = "512m",
        cpus: str = "0.50",
        dockerfile: str = "Dockerfile.hardened",
        use_image: bool = False,
    ) -> str:
        """
        Write a hardened docker-compose.yml and return its path.

        By default the service is built locally from `dockerfile`. It pulls `image` instead
        when use_image=True or when a non-placeholder image was passed explicitly (the CLI's
        --image flag).
        """
        if use_image or (image and image != "myorg/myapp:1.0.0" and not image.startswith("myorg/myservice")):
            # An explicitly chosen prebuilt image takes precedence over a local build.
            source = f"    image: {image}\n"
        else:
            source = (
                "    build:\n"
                "      context: .\n"
                f"      dockerfile: {dockerfile}\n"
            )

        # deploy.resources.limits (Swarm) spells megabytes with an uppercase suffix: 512m -> 512M.
        mem_deploy = mem_limit.upper() if mem_limit[-1:].lower() == "m" else mem_limit

        content = f"""# Generated by agentes (devops agent).
# deploy.resources only applies under Docker Swarm, while `docker compose` honours
# mem_limit and cpus, so both are declared.
version: '3.8'

services:
  {service_name}:
{source}    ports:
      - "{port}:{port}"
    restart: unless-stopped
    read_only: true
    tmpfs:
      - /tmp
    mem_limit: {mem_limit}
    cpus: {cpus}
    mem_reservation: 128m
    deploy:
      resources:
        limits:
          cpus: '{cpus}'
          memory: {mem_deploy}
        reservations:
          cpus: '0.10'
          memory: 128M
    networks:
      - app_internal_network
    security_opt:
      - no-new-privileges:true

networks:
  app_internal_network:
    driver: bridge
    internal: false
"""
        dirpath = os.path.dirname(os.path.abspath(output_filepath))
        os.makedirs(dirpath, exist_ok=True)
        with open(output_filepath, "w", encoding="utf-8") as f:
            f.write(content)
        return output_filepath
